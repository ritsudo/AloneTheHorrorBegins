import os
import numpy as np
from PIL import Image, ImageDraw, ImageFont

RES = r"C:\Users\Admin\j2mewtk\2.5.2\apps\AloneTheHorror\res"
SRC = r"C:\Users\Admin\j2mewtk\2.5.2\apps\AloneTheHorror\src"

CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,!?'\":;-()/&*+<>_[]%"

FONTS = [
    # name, ttf, size, xscale, yscale, class, space, colors {file: rgb}
    # Two sizes only, same serif face, drawn at natural width (no squish).
    ("font", r"C:\Windows\Fonts\timesbd.ttf", 13, 0.92, 1.0, "FntData", 6, {
        "font.png": (0x1A, 0x0A, 0x04),
        "font_red.png": (0xB0, 0x20, 0x18),
        "font_cream.png": (0xD8, 0xC0, 0xA0),
    }),
    ("font_big", r"C:\Windows\Fonts\timesbd.ttf", 18, 0.85, 1.25, "FntDataBig", 6, {
        "font_big.png": (0x1A, 0x0A, 0x04),
        "font_big_cream.png": (0xD8, 0xC0, 0xA0),
    }),
]


def build(name, ttf, size, xscale, yscale, cls, space, colors):
    font = ImageFont.truetype(ttf, size)
    glyphs = {}
    for c in CHARS:
        img = Image.new("L", (80, 60), 0)
        ImageDraw.Draw(img).text((12, 12), c, fill=255, font=font)
        a = np.asarray(img)
        ys, xs = np.where(a > 110)
        if len(xs) == 0:
            glyphs[c] = (None, 0, 0, 0)
            continue
        x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
        g = Image.fromarray(a[y0:y1 + 1, x0:x1 + 1])
        if xscale != 1.0 or yscale != 1.0:
            g = g.resize((max(1, int(round(g.width * xscale))),
                          max(1, int(round(g.height * yscale)))), Image.LANCZOS)
        glyphs[c] = (np.asarray(g), x0 - 12, y0 - 12, 0)

    top = min(b for (g, lx, b, _) in glyphs.values() if g is not None)
    bot = max(b + g.shape[0] for (g, lx, b, _) in glyphs.values() if g is not None)
    H = bot - top
    pad = 1
    strip_w = sum((g.shape[1] if g is not None else 3) + 2 * pad for (g, lx, b, _) in glyphs.values()) + 4

    mask = Image.new("L", (strip_w, H + 2 * pad), 0)
    x = pad
    for c in CHARS:
        g, lx, b, _ = glyphs[c]
        if g is None:
            x += 3 + 2 * pad
            continue
        gh, gw = g.shape
        mask.paste(Image.fromarray((g > 110).astype(np.uint8) * 255), (x, (b - top) + pad))
        x += gw + 2 * pad

    ma = np.asarray(mask)

    gx = [-1] * 128
    gw = [0] * 128
    adv = [0] * 128
    x = pad
    for c in CHARS:
        g, lx, b, _ = glyphs[c]
        o = ord(c)
        if o < 128:
            gx[o] = x
            gw[o] = (g.shape[1] if g is not None else 0)
            adv[o] = gw[o] + 1
        x += (g.shape[1] if g is not None else 3) + 2 * pad

    adv[32] = space

    def jarr(name, vals):
        return "    static final int[] %s = {%s};" % (name, ",".join(str(v) for v in vals))

    j = ["// generated by font_gen.py - do not edit", "class %s {" % cls,
         "    static final int H = %d;" % H,
         jarr("GX", gx), jarr("GW", gw), jarr("ADV", adv), "}"]
    open(os.path.join(SRC, cls + ".java"), "w").write("\n".join(j) + "\n")

    for fname, col in colors.items():
        rgba = np.zeros((mask.height, mask.width, 4), np.uint8)
        rgba[:, :, 0] = col[0]
        rgba[:, :, 1] = col[1]
        rgba[:, :, 2] = col[2]
        rgba[:, :, 3] = ma
        Image.fromarray(rgba, "RGBA").save(os.path.join(RES, fname))
        print("saved", fname, (mask.width, mask.height), "top", top, "H", H, "space", adv[32])


for args in FONTS:
    build(*args)
